import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { escapeHtml, renderHtmlReport } from './html';
import {
  SAMPLE_SPECS,
  reportForSample,
  type SampleSpec,
} from './samples';
import type { JsonReport } from './report';

const INDEX_STYLE = [
  'body{font-family:system-ui,sans-serif;max-width:860px;margin:2rem auto;padding:0 1rem;color:#1b1b1b;line-height:1.45}',
  'a{color:#1a4f8b}',
  'table{border-collapse:collapse;width:100%}',
  'th,td{border:1px solid #ddd;padding:.45rem .6rem;text-align:left;vertical-align:top}',
  'th{background:#f6f6f6}',
  '.sev{display:inline-block;padding:.1rem .5rem;border-radius:4px;color:#fff;font-weight:600;font-size:.85rem}',
  '.sev-info{background:#2f6fb3}.sev-warn{background:#b7791f}.sev-high{background:#c53030}',
  'footer{margin-top:2rem;color:#555;font-size:.9rem}',
].join('');

export type SamplePageFile = {
  filename: string;
  html: string;
};

export type SampleIndexRow = {
  spec: SampleSpec;
  report: JsonReport;
  href: string;
};

/** Filename used for a sample's standalone HTML page. */
export function samplePageFilename(id: string): string {
  return `${id}.html`;
}

function indexRow(spec: SampleSpec): SampleIndexRow {
  return {
    spec,
    report: reportForSample(spec),
    href: samplePageFilename(spec.id),
  };
}

/**
 * Landing page that lists every catalog sample with type, severity, and
 * a link to the matching standalone report. No scripts, no remote assets.
 */
export function renderSampleIndex(
  specs: readonly SampleSpec[] = SAMPLE_SPECS
): string {
  const rows = specs.map(indexRow);
  const tableBody = rows
    .map(({ spec, report, href }) => {
      const sev = report.severity;
      return [
        '<tr>',
        `<td><a href="${escapeHtml(href)}">${escapeHtml(spec.title)}</a></td>`,
        `<td><code>${escapeHtml(report.type)}</code></td>`,
        `<td><span class="sev sev-${sev}">${sev}</span></td>`,
        `<td>${escapeHtml(spec.summary)}</td>`,
        '</tr>',
      ].join('');
    })
    .join('');

  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>tx-sim-risk sample reports</title>',
    `<style>${INDEX_STYLE}</style>`,
    '</head>',
    '<body>',
    '<h1>tx-sim-risk sample reports</h1>',
    '<p>Static HTML reports generated from the built-in sample catalog. Each page is the same script-free renderer the CLI prints with <code>--html</code>.</p>',
    '<table>',
    '<thead><tr><th>Sample</th><th>Type</th><th>Severity</th><th>What it shows</th></tr></thead>',
    `<tbody>${tableBody}</tbody>`,
    '</table>',
    `<footer>${rows.length} samples. Regenerated by <code>npm run pages</code>.</footer>`,
    '</body>',
    '</html>',
    '',
  ].join('\n');
}

function renderLinkedSamplePage(spec: SampleSpec): string {
  const report = reportForSample(spec);
  return renderHtmlReport(report, spec.title, {
    preambleHtml:
      '<p><a href="./index.html">All sample reports</a></p>',
  });
}

/**
 * Build the full static site in memory: `index.html` plus one page per
 * sample. The index is always first.
 */
export function buildSampleSite(
  specs: readonly SampleSpec[] = SAMPLE_SPECS
): SamplePageFile[] {
  const files: SamplePageFile[] = [
    { filename: 'index.html', html: renderSampleIndex(specs) },
  ];
  for (const spec of specs) {
    files.push({
      filename: samplePageFilename(spec.id),
      html: renderLinkedSamplePage(spec),
    });
  }
  return files;
}

/**
 * Write the sample gallery to `outDir`, including an empty `.nojekyll`
 * so GitHub Pages serves the files as-is. Returns the written filenames
 * relative to `outDir`.
 */
export function writeSampleSite(
  outDir: string,
  specs: readonly SampleSpec[] = SAMPLE_SPECS
): string[] {
  mkdirSync(outDir, { recursive: true });
  const files = buildSampleSite(specs);
  for (const file of files) {
    writeFileSync(join(outDir, file.filename), file.html, 'utf8');
  }
  writeFileSync(join(outDir, '.nojekyll'), '', 'utf8');
  return [...files.map((file) => file.filename), '.nojekyll'];
}
